[CmdletBinding()]
param([ValidateSet('System','Security','Enterprise','All')][string]$Scope='All',[string]$AccessPath,[ValidatePattern('^[A-Za-z0-9][A-Za-z0-9.-]{0,252}$')][string]$TlsHost)
$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'COC.Core.psm1') -Force
$root = [IO.Path]::GetPathRoot($PSScriptRoot)
$session = New-CocSession -Root $root -Category Diagnostics
$checks=New-Object 'System.Collections.Generic.List[object]'
function Save-Check {
    param([string]$Name,[scriptblock]$Action)
    $path = Join-Path $session.Path $Name
    try { $text=& $Action *>&1 | Out-String -Width 240; Protect-CocReportText $text | Set-Content -LiteralPath $path -Encoding UTF8; $checks.Add([pscustomobject]@{Check=$Name;Result='PASS';Meaning='Collection completed; not a health/compliance certification'}) }
    catch { Protect-CocReportText ('CHECK UNAVAILABLE: ' + $_.Exception.Message) | Set-Content -LiteralPath $path -Encoding UTF8; $checks.Add([pscustomobject]@{Check=$Name;Result='BLOCKED';Meaning=$_.Exception.Message}) }
}
function Run-Native {
    param([string]$File,[string[]]$Arguments)
    & (Join-Path "$env:SystemRoot\System32" $File) @Arguments 2>&1
    $code=$LASTEXITCODE
    'Exit code: ' + $code
    if($code -ne 0){throw "Native check $File returned $code."}
}
try {
    if ($Scope -in @('System','All')) {
        $previousOutput = $env:COC_REPORT_OUTPUT
        try {
            $env:COC_REPORT_OUTPUT = $session.Path
            Save-Check 'system.txt' {
                & (Join-Path $root 'Tools\Windows\Technician-Scripts\Laptop-Diagnostics.ps1')
                'Detailed system/hardware evidence was generated by the existing canonical Laptop-Diagnostics collector.'
            }
            Save-Check 'network.txt' {
                & (Join-Path $root 'Scripts\Network\COC-Network-Diagnostics.ps1')
                'Detailed network evidence was generated by the existing canonical network collector.'
            }
        } finally { $env:COC_REPORT_OUTPUT = $previousOutput }
    }
    if ($Scope -in @('Security','All')) {
        Save-Check 'security.txt' {
            'Defender status'; try { Get-MpComputerStatus | Select-Object AMServiceEnabled,AntivirusEnabled,RealTimeProtectionEnabled,AntivirusSignatureLastUpdated } catch { $_.Exception.Message }
            'Firewall profiles'; Get-NetFirewallProfile | Select-Object Name,Enabled,DefaultInboundAction,DefaultOutboundAction
            'BitLocker status only; no protectors or recovery keys'; Run-Native 'manage-bde.exe' @('-status')
            'Secure Boot'; try { Confirm-SecureBootUEFI } catch { $_.Exception.Message }
            'TPM'; try { Get-Tpm | Select-Object TpmPresent,TpmReady,TpmEnabled,TpmActivated } catch { $_.Exception.Message }
            'Hotfix inventory (not complete update compliance)'; Get-HotFix | Select-Object HotFixID,InstalledOn
            'UAC configuration'; Get-ItemProperty -LiteralPath 'HKLM:\SOFTWARE\Microsoft\Windows\CurrentVersion\Policies\System' | Select-Object EnableLUA,ConsentPromptBehaviorAdmin,ConsentPromptBehaviorUser,PromptOnSecureDesktop
        }
        Save-Check 'firewall.csv' { Get-NetFirewallRule -PolicyStore ActiveStore | Select-Object DisplayName,Enabled,Direction,Action,Profile | ConvertTo-Csv -NoTypeInformation }
        Save-Check 'tasks.txt' { Get-ScheduledTask | Select-Object TaskPath,TaskName,State; 'Task actions and credentials are not exported.' }
        Save-Check 'services.txt' { Get-Service | Select-Object Name,DisplayName,Status,StartType }
        Save-Check 'certificates.txt' {
            foreach($store in @('Cert:\LocalMachine\My','Cert:\LocalMachine\Root','Cert:\CurrentUser\My')){
                "Store: $store"; Get-ChildItem -LiteralPath $store | Select-Object Subject,Issuer,NotBefore,NotAfter,Thumbprint
            }
            'Private keys and certificate contents are not exported.'
        }
        if($AccessPath){Save-Check 'permissions.txt' { Get-Acl -LiteralPath $AccessPath | Select-Object Owner,AccessToString; Run-Native 'icacls.exe' @($AccessPath) }}
        if($TlsHost){Save-Check 'tls.txt' {
            $client=New-Object Net.Sockets.TcpClient
            try{
                $connect=$client.ConnectAsync($TlsHost,443)
                if(-not $connect.Wait(5000)){throw 'TLS endpoint connect timeout.'}
                $client.ReceiveTimeout=5000;$client.SendTimeout=5000
                $ssl=New-Object Net.Security.SslStream($client.GetStream(),$false)
                try{$ssl.ReadTimeout=5000;$ssl.WriteTimeout=5000;$ssl.AuthenticateAsClient($TlsHost);[pscustomobject]@{Host=$TlsHost;Protocol=$ssl.SslProtocol;Authenticated=$ssl.IsAuthenticated;Certificate=$ssl.RemoteCertificate.Subject}}
                finally{$ssl.Dispose()}
            }finally{$client.Dispose()}
        }}
    }
    if ($Scope -in @('Enterprise','All')) {
        Save-Check 'enterprise.txt' {
            'Device registration'; Run-Native 'dsregcmd.exe' @('/status')
            'Applied policy'; Run-Native 'gpresult.exe' @('/r')
            'Windows time status'; Run-Native 'w32tm.exe' @('/query','/status')
            'Enterprise services'; Get-Service -Name Netlogon,LanmanWorkstation,BITS,wuauserv -ErrorAction Continue | Select-Object Name,Status,StartType
            'No domain changes or secure-channel repair are performed.'
            $computer=Get-CimInstance Win32_ComputerSystem
            if($computer.PartOfDomain){'Domain secure channel status';Run-Native 'nltest.exe' @('/sc_query:'+$computer.Domain)}else{'Domain checks: not domain joined.'}
            'Kerberos ticket metadata (no ticket export)';Run-Native 'klist.exe' @()
        }
        Save-Check 'activation.txt' { Get-CimInstance SoftwareLicensingProduct | Where-Object { $_.Name -like 'Windows*' -and $_.PartialProductKey } | Select-Object Name,Description,LicenseStatus,GracePeriodRemaining; 'LicenseStatus 1 is licensed; do not infer transfer rights from activation.' }
        Save-Check 'printers.txt' { Get-Service -Name Spooler; $printers=@(Get-Printer); $printers | Select-Object Name,DriverName,PortName,PrinterStatus,JobCount; foreach($printer in $printers){Get-PrintJob -PrinterName $printer.Name -ErrorAction Continue | Select-Object ID,JobStatus,Size} }
        Save-Check 'drivers.txt' { Get-CimInstance Win32_PnPSignedDriver | Select-Object DeviceName,DeviceID,DriverVersion,DriverDate,InfName,Manufacturer,IsSigned }
        Save-Check 'crash-dumps.txt' { Get-ChildItem -LiteralPath "$env:SystemRoot\Minidump" -File -ErrorAction Continue | Select-Object Name,Length,LastWriteTime; Get-Item -LiteralPath "$env:SystemRoot\MEMORY.DMP" -ErrorAction Continue | Select-Object Name,Length,LastWriteTime; 'Dump contents were not copied.' }
    }
} finally { $checks|Export-Csv -LiteralPath (Join-Path $session.Path 'check-status.csv') -NoTypeInformation; Complete-CocSession $session }
Write-Host "Reports saved: $($session.Path)"
Write-Host 'Some checks need elevation or enterprise membership. Reports contain sensitive device/user/network context; control access.'
if(@($checks|Where-Object Result -eq 'BLOCKED').Count){exit 2};exit 0

